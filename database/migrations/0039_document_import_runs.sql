SET LOCAL ROLE app_owner;

-- ADR-064：文档导入批次表。每次成功执行（项目内导入或整项目导入）写入一行，
-- 记录文档摘要、模板版本、操作者与各层数量；同一项目内同一摘要只允许存在一行，
-- 重复导入必须在应用层 409（本表唯一约束是最后防线，也是预览查重与审计溯源的依据）。
-- 口径：
--   1. 运行记录不可更新、不可删除（除项目物理删除级联清理），因此 app_runtime 只有
--      SELECT / INSERT，没有 UPDATE / DELETE；
--   2. document_digest 为规范化文档文本（去 BOM、CRLF→LF）的 SHA-256 十六进制，
--      模板版本变化时旧摘要行保留，供历史解释；
--   3. 行内只保存计数，不保存文档原文、解析结果或任何用户正文；
--   4. 项目物理删除（app.purge_project）在删除项目行之前显式清空本表，删除完成后
--      同一文档可以重新导入到新项目。

CREATE TABLE app.document_import_runs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL,
  document_digest TEXT NOT NULL,
  template_version TEXT NOT NULL,
  actor_id INTEGER NOT NULL,
  module_count INTEGER NOT NULL,
  feature_count INTEGER NOT NULL,
  task_count INTEGER NOT NULL,
  reused_module_count INTEGER NOT NULL,
  reused_feature_count INTEGER NOT NULL,
  added_member_count INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT document_import_runs_project_fk
    FOREIGN KEY (project_id) REFERENCES app.projects(id)
    ON DELETE restrict ON UPDATE no action,
  CONSTRAINT document_import_runs_actor_fk
    FOREIGN KEY (actor_id) REFERENCES app.users(id)
    ON DELETE restrict ON UPDATE no action,
  CONSTRAINT document_import_runs_project_digest_unique
    UNIQUE (project_id, document_digest),
  CONSTRAINT document_import_runs_digest_check
    CHECK (document_digest ~ '^[0-9a-f]{64}$'),
  CONSTRAINT document_import_runs_template_version_check
    CHECK (template_version = '1'),
  CONSTRAINT document_import_runs_counts_check
    CHECK (
      module_count >= 0
      AND feature_count >= 0
      AND task_count >= 0
      AND reused_module_count >= 0
      AND reused_feature_count >= 0
      AND added_member_count >= 0
    )
);

-- 整项目导入在项目尚不存在时按摘要全局查重；该索引同时服务预览提示。
CREATE INDEX document_import_runs_digest_idx
  ON app.document_import_runs (document_digest);

GRANT SELECT, INSERT ON app.document_import_runs TO app_runtime;
GRANT USAGE, SELECT ON SEQUENCE app.document_import_runs_id_seq TO app_runtime;
-- 新表显式补备份只读授权（ADR-020 fail closed：不依赖 ALTER DEFAULT PRIVILEGES）。
GRANT SELECT ON app.document_import_runs TO app_backup;
GRANT USAGE, SELECT ON SEQUENCE app.document_import_runs_id_seq TO app_backup;

-- 项目物理删除清单补上批次表：在删除项目行之前清空，删除后同一文档可重新导入。
CREATE OR REPLACE FUNCTION app.purge_project(p_project_id INTEGER)
 RETURNS TABLE (
   modules INTEGER,
   features INTEGER,
   tasks INTEGER,
   change_records INTEGER,
   audit_logs INTEGER,
   members INTEGER,
   total INTEGER
 )
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'app'
AS $function$
DECLARE
  v_removed INTEGER;
  v_modules INTEGER := 0;
  v_features INTEGER := 0;
  v_tasks INTEGER := 0;
  v_change_records INTEGER := 0;
  v_audit_logs INTEGER := 0;
  v_members INTEGER := 0;
  v_total INTEGER := 0;
BEGIN
  IF p_project_id IS NULL OR p_project_id <= 0 THEN
    RAISE EXCEPTION 'project id must be a positive integer'
      USING ERRCODE = 'check_violation';
  END IF;

  -- 项目必须真实存在；`FOR UPDATE` 让同项目的写路径在删除期间排队等待，
  -- 并发的两次删除只有一个能命中这一行。
  IF NOT EXISTS (
    SELECT 1
      FROM app.projects p
     WHERE p.id = p_project_id
     FOR UPDATE
  ) THEN
    RAISE EXCEPTION 'project % not found', p_project_id
      USING ERRCODE = 'check_violation';
  END IF;

  -- 事务级豁免开关：只对本次 purge 的项目放开未分类模块删除防线。
  PERFORM set_config('app.purge_project_id', p_project_id::text, true);

  DELETE FROM app.change_record_version_leftovers r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.change_record_external_links r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.change_record_feature_impacts r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.change_record_versions r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.leftover_task_links r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.change_record_leftover_items r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.change_records r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_change_records := v_change_records + v_removed;
  v_total := v_total + v_removed;

  DELETE FROM app.task_feature_impacts r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.task_group_members r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.task_status_history r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.task_assignees r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.task_external_links r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.tasks r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_tasks := v_tasks + v_removed;
  v_total := v_total + v_removed;

  DELETE FROM app.task_groups r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.feature_external_links r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.features r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_features := v_features + v_removed;
  v_total := v_total + v_removed;

  DELETE FROM app.project_external_links r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  -- 未分类模块由上面的触发器豁免放行；其余模块没有删除防线。
  DELETE FROM app.modules m WHERE m.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_modules := v_modules + v_removed;
  v_total := v_total + v_removed;

  DELETE FROM app.project_archive_requests r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.code_sequences r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  -- ADR-064：文档导入批次记录随项目一起物理删除；项目删除后同一文档可重新导入。
  DELETE FROM app.document_import_runs r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.project_members r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_members := v_members + v_removed;
  v_total := v_total + v_removed;

  DELETE FROM app.notifications r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.activity_projection r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.search_projection r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.external_links r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  -- 项目自己的审计链随项目一起消失；SYSTEM 链只新增一条 project.delete（由 API 写）。
  DELETE FROM app.audit_logs r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_audit_logs := v_audit_logs + v_removed;
  v_total := v_total + v_removed;

  DELETE FROM app.audit_chain_heads r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.projects r WHERE r.id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  IF v_removed <> 1 THEN
    RAISE EXCEPTION 'project % disappeared during purge', p_project_id;
  END IF;

  PERFORM set_config('app.purge_project_id', '', true);

  RETURN QUERY
    SELECT v_modules,
           v_features,
           v_tasks,
           v_change_records,
           v_audit_logs,
           v_members,
           v_total;
END
$function$;

-- 部署校验：表、唯一约束、最小授权与 purge 清单必须同时成立。
DO $$
DECLARE
  table_owner TEXT;
  unique_constraint INTEGER;
  runtime_select BOOLEAN;
  runtime_insert BOOLEAN;
  runtime_update BOOLEAN;
  runtime_delete BOOLEAN;
  backup_select BOOLEAN;
  backup_insert BOOLEAN;
  purge_owner TEXT;
  purge_def TEXT;
  runtime_can_execute BOOLEAN;
  public_can_execute BOOLEAN;
BEGIN
  SELECT pg_get_userbyid(c.relowner)
    INTO table_owner
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'app'
     AND c.relname = 'document_import_runs'
     AND c.relkind = 'r';

  IF table_owner IS NULL THEN
    RAISE EXCEPTION 'app.document_import_runs was not created';
  END IF;
  IF table_owner <> 'app_owner' THEN
    RAISE EXCEPTION 'app.document_import_runs must be owned by app_owner, got %', table_owner;
  END IF;

  SELECT count(*)
    INTO unique_constraint
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
   WHERE n.nspname = 'app'
     AND t.relname = 'document_import_runs'
     AND c.conname = 'document_import_runs_project_digest_unique'
     AND c.contype = 'u';

  IF unique_constraint <> 1 THEN
    RAISE EXCEPTION 'document_import_runs_project_digest_unique is missing';
  END IF;

  SELECT has_table_privilege('app_runtime', 'app.document_import_runs', 'SELECT'),
         has_table_privilege('app_runtime', 'app.document_import_runs', 'INSERT'),
         has_table_privilege('app_runtime', 'app.document_import_runs', 'UPDATE'),
         has_table_privilege('app_runtime', 'app.document_import_runs', 'DELETE')
    INTO runtime_select, runtime_insert, runtime_update, runtime_delete;

  IF NOT runtime_select OR NOT runtime_insert THEN
    RAISE EXCEPTION 'app_runtime must have SELECT and INSERT on app.document_import_runs';
  END IF;
  IF runtime_update OR runtime_delete THEN
    RAISE EXCEPTION 'app_runtime must not have UPDATE or DELETE on app.document_import_runs';
  END IF;

  SELECT has_table_privilege('app_backup', 'app.document_import_runs', 'SELECT'),
         has_table_privilege('app_backup', 'app.document_import_runs', 'INSERT')
    INTO backup_select, backup_insert;

  IF NOT backup_select OR backup_insert THEN
    RAISE EXCEPTION 'app_backup must have read-only access to app.document_import_runs';
  END IF;

  SELECT pg_get_userbyid(p.proowner), pg_get_functiondef(p.oid)
    INTO purge_owner, purge_def
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname = 'app'
     AND p.proname = 'purge_project';

  IF purge_owner IS NULL OR purge_owner <> 'app_owner' THEN
    RAISE EXCEPTION 'app.purge_project ownership check failed';
  END IF;
  IF position('document_import_runs' IN purge_def) = 0 THEN
    RAISE EXCEPTION 'app.purge_project must delete app.document_import_runs';
  END IF;

  SELECT has_function_privilege('app_runtime', 'app.purge_project(integer)', 'EXECUTE'),
         has_function_privilege('public', 'app.purge_project(integer)', 'EXECUTE')
    INTO runtime_can_execute, public_can_execute;

  IF NOT runtime_can_execute OR public_can_execute THEN
    RAISE EXCEPTION 'app.purge_project execute grants are wrong';
  END IF;
END
$$;