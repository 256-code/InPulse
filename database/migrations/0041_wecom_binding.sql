SET LOCAL ROLE app_owner;

-- ADR-069：企业微信机器人绑定（阶段一：一次性绑定码与绑定关系）。
-- 口径：
--   1. app.wecom_binding_codes 每个用户最多一行「当前待用绑定码」：明文码永不
--      入库，只存 SHA-256 Hash（32 字节）与有效期；重新生成覆盖同一行，旧码
--      立即失效；10 分钟有效、一次性消费（consumed_at 非空即不可用，包含被
--      重新生成取代或用户主动撤销的情形，此时 consumed_by_wecom_userid 为空）。
--   2. app.user_wecom_bindings 记录「企微 userid ↔ InPulse 用户」绑定：同一
--      用户最多一条 ACTIVE；同一 wecom_userid 最多一条 ACTIVE（部分唯一索引
--      兜底）；解绑是 REVOKED 状态流转，永不物理删除；重绑更新原行。
--   3. 绑定码兑换只能通过 app.redeem_wecom_binding_code 在单事务内完成：
--      按 code_hash 唯一索引取行并 FOR UPDATE，条件消费 + 唯一索引兜底；
--      函数 SECURITY DEFINER 且 PUBLIC 执行权被回收，桥接进程以 app_runtime
--      角色调用；兑换函数不做任何网络调用，只操作数据库。
--   4. app_runtime 对两张表只有 SELECT / INSERT / UPDATE（无 DELETE）；
--      app_backup 只读授权显式补齐（ADR-020 fail closed）。
--   5. 兑换错误以自定义 SQLSTATE 区分：WBC01 无效码 / WBC02 已使用 /
--      WBC03 参数非法 / WBC04 用户已停用 / WBC05 已过期 / WBC06 企微账号已绑。

CREATE TABLE app.wecom_binding_codes (
  user_id INTEGER PRIMARY KEY,
  code_hash BYTEA NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  consumed_by_wecom_userid TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT wecom_binding_codes_hash_unique UNIQUE (code_hash),
  CONSTRAINT wecom_binding_codes_hash_check
    CHECK (octet_length(code_hash) = 32),
  CONSTRAINT wecom_binding_codes_expiry_check CHECK (expires_at > created_at),
  CONSTRAINT wecom_binding_codes_consumed_check
    CHECK (consumed_at IS NULL OR consumed_at >= created_at),
  CONSTRAINT wecom_binding_codes_consumer_check
    CHECK (consumed_by_wecom_userid IS NULL OR consumed_at IS NOT NULL),
  CONSTRAINT wecom_binding_codes_consumer_length_check
    CHECK (
      consumed_by_wecom_userid IS NULL
      OR length(consumed_by_wecom_userid) BETWEEN 1 AND 128
    ),
  CONSTRAINT wecom_binding_codes_user_fk
    FOREIGN KEY (user_id) REFERENCES app.users(id)
    ON DELETE restrict ON UPDATE no action
);

CREATE TABLE app.user_wecom_bindings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  wecom_userid TEXT NOT NULL,
  status TEXT NOT NULL,
  bound_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  row_version INTEGER NOT NULL DEFAULT 1,
  CONSTRAINT user_wecom_bindings_status_check
    CHECK (status IN ('ACTIVE', 'REVOKED')),
  CONSTRAINT user_wecom_bindings_state_check
    CHECK (
      (status = 'ACTIVE' AND revoked_at IS NULL)
      OR (status = 'REVOKED' AND revoked_at IS NOT NULL)
    ),
  CONSTRAINT user_wecom_bindings_wecom_userid_check
    CHECK (length(wecom_userid) BETWEEN 1 AND 128),
  CONSTRAINT user_wecom_bindings_row_version_check CHECK (row_version >= 1),
  CONSTRAINT user_wecom_bindings_user_fk
    FOREIGN KEY (user_id) REFERENCES app.users(id)
    ON DELETE restrict ON UPDATE no action
);

CREATE UNIQUE INDEX user_wecom_bindings_active_user_idx
  ON app.user_wecom_bindings (user_id)
  WHERE status = 'ACTIVE';
CREATE UNIQUE INDEX user_wecom_bindings_active_wecom_idx
  ON app.user_wecom_bindings (wecom_userid)
  WHERE status = 'ACTIVE';

CREATE FUNCTION app.redeem_wecom_binding_code(
  p_code_hash BYTEA,
  p_wecom_userid TEXT
)
RETURNS TABLE (user_id INTEGER, display_name TEXT)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = app, pg_catalog
AS $$
DECLARE
  v_code app.wecom_binding_codes%ROWTYPE;
  v_user_name TEXT;
  v_user_status TEXT;
  v_conflict_user_id INTEGER;
BEGIN
  IF p_code_hash IS NULL OR octet_length(p_code_hash) <> 32 THEN
    RAISE EXCEPTION 'code hash must be 32 bytes' USING ERRCODE = 'WBC03';
  END IF;
  IF p_wecom_userid IS NULL
     OR length(p_wecom_userid) NOT BETWEEN 1 AND 128 THEN
    RAISE EXCEPTION 'wecom userid is invalid' USING ERRCODE = 'WBC03';
  END IF;

  SELECT c.*
    INTO v_code
    FROM app.wecom_binding_codes AS c
   WHERE c.code_hash = p_code_hash
   FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'binding code not found' USING ERRCODE = 'WBC01';
  END IF;
  IF v_code.consumed_at IS NOT NULL THEN
    RAISE EXCEPTION 'binding code already used' USING ERRCODE = 'WBC02';
  END IF;
  IF v_code.expires_at <= now() THEN
    RAISE EXCEPTION 'binding code expired' USING ERRCODE = 'WBC05';
  END IF;

  SELECT u.name, u.status
    INTO v_user_name, v_user_status
    FROM app.users AS u
   WHERE u.id = v_code.user_id;

  IF v_user_status IS DISTINCT FROM 'ACTIVE' THEN
    RAISE EXCEPTION 'user is not active' USING ERRCODE = 'WBC04';
  END IF;

  SELECT b.user_id
    INTO v_conflict_user_id
    FROM app.user_wecom_bindings AS b
   WHERE b.wecom_userid = p_wecom_userid
     AND b.status = 'ACTIVE'
   FOR UPDATE;

  IF FOUND AND v_conflict_user_id <> v_code.user_id THEN
    RAISE EXCEPTION 'wecom userid already bound' USING ERRCODE = 'WBC06';
  END IF;

  UPDATE app.user_wecom_bindings AS b
     SET wecom_userid = p_wecom_userid,
         bound_at = now(),
         updated_at = now(),
         row_version = b.row_version + 1
   WHERE b.user_id = v_code.user_id
     AND b.status = 'ACTIVE';

  IF NOT FOUND THEN
    INSERT INTO app.user_wecom_bindings (user_id, wecom_userid, status)
    VALUES (v_code.user_id, p_wecom_userid, 'ACTIVE');
  END IF;

  UPDATE app.wecom_binding_codes AS c
     SET consumed_at = now(),
         consumed_by_wecom_userid = p_wecom_userid
   WHERE c.user_id = v_code.user_id;

  RETURN QUERY SELECT v_code.user_id, v_user_name;
EXCEPTION
  WHEN unique_violation THEN
    RAISE EXCEPTION 'wecom userid already bound' USING ERRCODE = 'WBC06';
END;
$$;

REVOKE ALL ON FUNCTION app.redeem_wecom_binding_code(BYTEA, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION app.redeem_wecom_binding_code(BYTEA, TEXT) TO app_runtime;

GRANT SELECT, INSERT, UPDATE ON app.wecom_binding_codes TO app_runtime;
GRANT SELECT, INSERT, UPDATE ON app.user_wecom_bindings TO app_runtime;
GRANT USAGE, SELECT ON SEQUENCE app.user_wecom_bindings_id_seq TO app_runtime;

GRANT SELECT ON app.wecom_binding_codes TO app_backup;
GRANT SELECT ON app.user_wecom_bindings TO app_backup;
GRANT USAGE, SELECT ON SEQUENCE app.user_wecom_bindings_id_seq TO app_backup;

-- 部署校验：表、索引、函数与最小授权必须同时成立。
DO $$
DECLARE
  codes_owner TEXT;
  bindings_owner TEXT;
  active_user_idx INTEGER;
  active_wecom_idx INTEGER;
  codes_hash_unique INTEGER;
  function_security_definer BOOLEAN;
  function_owner TEXT;
  function_has_explicit_acl BOOLEAN;
  runtime_function_execute BOOLEAN;
  runtime_ok BOOLEAN;
  backup_ok BOOLEAN;
BEGIN
  SELECT pg_get_userbyid(c.relowner)
    INTO codes_owner
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'app'
     AND c.relname = 'wecom_binding_codes'
     AND c.relkind = 'r';

  SELECT pg_get_userbyid(c.relowner)
    INTO bindings_owner
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'app'
     AND c.relname = 'user_wecom_bindings'
     AND c.relkind = 'r';

  IF codes_owner IS NULL OR bindings_owner IS NULL THEN
    RAISE EXCEPTION 'wecom binding tables were not created';
  END IF;
  IF codes_owner <> 'app_owner' OR bindings_owner <> 'app_owner' THEN
    RAISE EXCEPTION 'wecom binding tables must be owned by app_owner, got % / %',
      codes_owner, bindings_owner;
  END IF;

  SELECT count(*)
    INTO active_user_idx
    FROM pg_indexes
   WHERE schemaname = 'app'
     AND tablename = 'user_wecom_bindings'
     AND indexname = 'user_wecom_bindings_active_user_idx';

  SELECT count(*)
    INTO active_wecom_idx
    FROM pg_indexes
   WHERE schemaname = 'app'
     AND tablename = 'user_wecom_bindings'
     AND indexname = 'user_wecom_bindings_active_wecom_idx';

  SELECT count(*)
    INTO codes_hash_unique
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
   WHERE n.nspname = 'app'
     AND t.relname = 'wecom_binding_codes'
     AND c.conname = 'wecom_binding_codes_hash_unique'
     AND c.contype = 'u';

  IF active_user_idx <> 1 OR active_wecom_idx <> 1 OR codes_hash_unique <> 1 THEN
    RAISE EXCEPTION 'wecom binding unique constraints are incomplete';
  END IF;

  SELECT p.prosecdef, pg_get_userbyid(p.proowner), p.proacl IS NOT NULL
    INTO function_security_definer, function_owner, function_has_explicit_acl
    FROM pg_proc p
   WHERE p.oid = 'app.redeem_wecom_binding_code(bytea, text)'::regprocedure;

  IF function_security_definer IS NULL
     OR NOT function_security_definer
     OR function_owner <> 'app_owner'
     OR NOT function_has_explicit_acl THEN
    RAISE EXCEPTION 'app.redeem_wecom_binding_code must be SECURITY DEFINER owned by app_owner with explicit ACL';
  END IF;

  IF EXISTS (
    SELECT 1
      FROM pg_proc p,
           LATERAL aclexplode(p.proacl) AS acl
     WHERE p.oid = 'app.redeem_wecom_binding_code(bytea, text)'::regprocedure
       AND acl.grantee = 0
  ) THEN
    RAISE EXCEPTION 'PUBLIC must not execute app.redeem_wecom_binding_code';
  END IF;

  SELECT has_function_privilege(
           'app_runtime',
           'app.redeem_wecom_binding_code(bytea, text)',
           'EXECUTE'
         )
    INTO runtime_function_execute;
  IF NOT runtime_function_execute THEN
    RAISE EXCEPTION 'app_runtime must execute app.redeem_wecom_binding_code';
  END IF;

  SELECT
    has_table_privilege('app_runtime', 'app.wecom_binding_codes', 'SELECT')
    AND has_table_privilege('app_runtime', 'app.wecom_binding_codes', 'INSERT')
    AND has_table_privilege('app_runtime', 'app.wecom_binding_codes', 'UPDATE')
    AND NOT has_table_privilege('app_runtime', 'app.wecom_binding_codes', 'DELETE')
    AND has_table_privilege('app_runtime', 'app.user_wecom_bindings', 'SELECT')
    AND has_table_privilege('app_runtime', 'app.user_wecom_bindings', 'INSERT')
    AND has_table_privilege('app_runtime', 'app.user_wecom_bindings', 'UPDATE')
    AND NOT has_table_privilege('app_runtime', 'app.user_wecom_bindings', 'DELETE')
    INTO runtime_ok;
  IF NOT runtime_ok THEN
    RAISE EXCEPTION 'app_runtime must have SELECT / INSERT / UPDATE and no DELETE on wecom binding tables';
  END IF;

  SELECT
    has_table_privilege('app_backup', 'app.wecom_binding_codes', 'SELECT')
    AND NOT has_table_privilege('app_backup', 'app.wecom_binding_codes', 'INSERT')
    AND NOT has_table_privilege('app_backup', 'app.wecom_binding_codes', 'UPDATE')
    AND NOT has_table_privilege('app_backup', 'app.wecom_binding_codes', 'DELETE')
    AND has_table_privilege('app_backup', 'app.user_wecom_bindings', 'SELECT')
    AND NOT has_table_privilege('app_backup', 'app.user_wecom_bindings', 'INSERT')
    AND NOT has_table_privilege('app_backup', 'app.user_wecom_bindings', 'UPDATE')
    AND NOT has_table_privilege('app_backup', 'app.user_wecom_bindings', 'DELETE')
    INTO backup_ok;
  IF NOT backup_ok THEN
    RAISE EXCEPTION 'app_backup must have read-only access to wecom binding tables';
  END IF;
END
$$;
