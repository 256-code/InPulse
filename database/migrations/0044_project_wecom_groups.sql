SET LOCAL ROLE app_owner;

-- ADR-077：企业微信项目群绑定（阶段二消息投递的数据面）。
-- 口径：
--   1. app.project_wecom_binding_codes 每个项目最多一行「当前待用绑定码」：
--      明文码永不入库，只存 SHA-256 Hash（32 字节）与有效期；重新生成覆盖
--      同一行，旧码立即失效；10 分钟有效、一次性消费（consumed_at 非空即
--      不可用，包含被重新生成取代、被解绑作废或已兑换的情形）。
--   2. app.project_wecom_groups 记录「项目 ↔ 企业微信群」绑定：同一项目至多
--      一条 ACTIVE；同一个群至多一条 ACTIVE（部分唯一索引兜底）；解绑是
--      REVOKED 状态流转，永不物理删除；换绑 = 旧行 REVOKED + 新行 ACTIVE，
--      投递历史按绑定行保留。
--   3. 绑定兑换只能通过 app.redeem_project_wecom_binding_code 在单事务内完成：
--      先锁码行，再锁发送者个人绑定行，最后锁群绑定行（先 chat 后 project）；
--      校验发送者个人绑定与项目成员身份（系统管理员豁免成员校验）、处理
--      群冲突与换绑、消费码。函数 SECURITY DEFINER 且 PUBLIC 执行权被回收，
--      桥接进程以 app_runtime 角色调用；函数不做任何网络调用。
--   4. app.wecom_group_deliveries 是投递状态表（桥接侧改造为独立批次）：
--      按（绑定行，来源类型，来源 id）唯一去重，PENDING / SENT / FAILED 状态
--      流转，桥接重启后可从 PENDING 断点续传；本迁移只落表与授权。
--   5. app_runtime 对三张表只有 SELECT / INSERT / UPDATE（无 DELETE）；
--      app_backup 只读授权显式补齐（ADR-020 fail closed）。
--   6. 兑换错误以自定义 SQLSTATE 区分：PWG01 无效码 / PWG02 已使用 /
--      PWG03 发送者无可用绑定账号（未绑定或已停用）/ PWG04 发送者非项目成员 /
--      PWG05 群已绑定其它项目 / PWG06 已过期 / PWG07 参数非法 / PWG08 并发冲突。
--   7. 项目物理删除（app.purge_project）同步清理三张表：本迁移重定义函数体
--      并在部署断言中校验删除清单包含新表。

CREATE TABLE app.project_wecom_binding_codes (
  project_id INTEGER PRIMARY KEY,
  code_hash BYTEA NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  consumed_by_wecom_userid TEXT,
  consumed_by_user_id INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT project_wecom_binding_codes_hash_unique UNIQUE (code_hash),
  CONSTRAINT project_wecom_binding_codes_hash_check
    CHECK (octet_length(code_hash) = 32),
  CONSTRAINT project_wecom_binding_codes_expiry_check
    CHECK (expires_at > created_at),
  CONSTRAINT project_wecom_binding_codes_consumed_check
    CHECK (consumed_at IS NULL OR consumed_at >= created_at),
  CONSTRAINT project_wecom_binding_codes_consumer_check
    CHECK (consumed_by_wecom_userid IS NULL OR consumed_at IS NOT NULL),
  CONSTRAINT project_wecom_binding_codes_consumer_user_check
    CHECK (consumed_by_user_id IS NULL OR consumed_at IS NOT NULL),
  CONSTRAINT project_wecom_binding_codes_consumer_length_check
    CHECK (
      consumed_by_wecom_userid IS NULL
      OR length(consumed_by_wecom_userid) BETWEEN 1 AND 128
    ),
  CONSTRAINT project_wecom_binding_codes_project_fk
    FOREIGN KEY (project_id) REFERENCES app.projects(id)
    ON DELETE restrict ON UPDATE no action,
  CONSTRAINT project_wecom_binding_codes_consumer_user_fk
    FOREIGN KEY (consumed_by_user_id) REFERENCES app.users(id)
    ON DELETE restrict ON UPDATE no action
);

