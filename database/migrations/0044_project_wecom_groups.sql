-- 项目物理删除清单补上企微群绑定三张表（先投递、再绑定行、最后待用码）。
CREATE OR REPLACE FUNCTION app.purge_project(p_project_id INTEGER)
 RETURNS TABLE (
   modules INTEGER,
   features INTEGER,
   tasks INTEGER,
   change_records INTEGER,
   audit_logs INTEGER,
   members INTEGER,
   total INTEGER
 )
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'app'
AS $function$
DECLARE
  v_removed INTEGER;
  v_modules INTEGER := 0;
  v_features INTEGER := 0;
  v_tasks INTEGER := 0;
  v_change_records INTEGER := 0;
  v_audit_logs INTEGER := 0;
  v_members INTEGER := 0;
  v_total INTEGER := 0;
BEGIN
  IF p_project_id IS NULL OR p_project_id <= 0 THEN
    RAISE EXCEPTION 'project id must be a positive integer'
      USING ERRCODE = 'check_violation';
  END IF;

  IF NOT EXISTS (
    SELECT 1
      FROM app.projects p
     WHERE p.id = p_project_id
     FOR UPDATE
  ) THEN
    RAISE EXCEPTION 'project % not found', p_project_id
      USING ERRCODE = 'check_violation';
  END IF;

  PERFORM set_config('app.purge_project_id', p_project_id::text, true);

  DELETE FROM app.change_record_version_leftovers r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.change_record_external_links r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.change_record_feature_impacts r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.change_record_versions r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.leftover_task_links r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.change_record_leftover_items r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.change_records r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_change_records := v_change_records + v_removed;
  v_total := v_total + v_removed;

  DELETE FROM app.task_feature_impacts r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.task_group_members r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.task_status_history r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.task_assignees r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.task_external_links r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.tasks r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_tasks := v_tasks + v_removed;
  v_total := v_total + v_removed;

  DELETE FROM app.task_groups r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.feature_external_links r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.features r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_features := v_features + v_removed;
  v_total := v_total + v_removed;

  DELETE FROM app.project_external_links r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.modules m WHERE m.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_modules := v_modules + v_removed;
  v_total := v_total + v_removed;

  DELETE FROM app.project_archive_requests r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.code_sequences r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.document_import_runs r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  -- ADR-077：企微群投递记录与绑定行随项目一起物理删除，最后清待用码。
  DELETE FROM app.wecom_group_deliveries d
   USING app.project_wecom_groups g
   WHERE d.group_binding_id = g.id
     AND g.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.project_wecom_groups r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.project_wecom_binding_codes r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.project_members r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_members := v_members + v_removed;
  v_total := v_total + v_removed;

  DELETE FROM app.notifications r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.activity_projection r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.search_projection r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.external_links r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.audit_logs r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_audit_logs := v_audit_logs + v_removed;
  v_total := v_total + v_removed;

  DELETE FROM app.audit_chain_heads r WHERE r.project_id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  v_total := v_total + v_removed;

  DELETE FROM app.projects r WHERE r.id = p_project_id;
  GET DIAGNOSTICS v_removed = ROW_COUNT;
  IF v_removed <> 1 THEN
    RAISE EXCEPTION 'project % disappeared during purge', p_project_id;
  END IF;

  PERFORM set_config('app.purge_project_id', '', true);

  RETURN QUERY
    SELECT v_modules,
           v_features,
           v_tasks,
           v_change_records,
           v_audit_logs,
           v_members,
           v_total;
END;
$function$;

-- 部署校验：表、索引、函数、最小授权与 purge 清单必须同时成立。
DO $$
DECLARE
  codes_owner TEXT;
  groups_owner TEXT;
  deliveries_owner TEXT;
  active_project_idx INTEGER;
  active_chat_idx INTEGER;
  pending_idx INTEGER;
  deliveries_unique INTEGER;
  function_security_definer BOOLEAN;
  function_owner TEXT;
  function_has_explicit_acl BOOLEAN;
  runtime_function_execute BOOLEAN;
  runtime_ok BOOLEAN;
  backup_ok BOOLEAN;
  purge_owner TEXT;
  purge_def TEXT;
BEGIN
  SELECT pg_get_userbyid(c.relowner)
    INTO codes_owner
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'app'
     AND c.relname = 'project_wecom_binding_codes'
     AND c.relkind = 'r';

  SELECT pg_get_userbyid(c.relowner)
    INTO groups_owner
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'app'
     AND c.relname = 'project_wecom_groups'
     AND c.relkind = 'r';

  SELECT pg_get_userbyid(c.relowner)
    INTO deliveries_owner
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'app'
     AND c.relname = 'wecom_group_deliveries'
     AND c.relkind = 'r';

  IF codes_owner IS NULL OR groups_owner IS NULL OR deliveries_owner IS NULL THEN
    RAISE EXCEPTION 'project wecom group tables were not created';
  END IF;
  IF codes_owner <> 'app_owner'
     OR groups_owner <> 'app_owner'
     OR deliveries_owner <> 'app_owner' THEN
    RAISE EXCEPTION
      'project wecom group tables must be owned by app_owner, got % / % / %',
      codes_owner, groups_owner, deliveries_owner;
  END IF;

  SELECT count(*)
    INTO active_project_idx
    FROM pg_indexes
   WHERE schemaname = 'app'
     AND tablename = 'project_wecom_groups'
     AND indexname = 'project_wecom_groups_active_project_idx';

  SELECT count(*)
    INTO active_chat_idx
    FROM pg_indexes
   WHERE schemaname = 'app'
     AND tablename = 'project_wecom_groups'
     AND indexname = 'project_wecom_groups_active_chat_idx';

  SELECT count(*)
    INTO pending_idx
    FROM pg_indexes
   WHERE schemaname = 'app'
     AND tablename = 'wecom_group_deliveries'
     AND indexname = 'wecom_group_deliveries_pending_idx';

  SELECT count(*)
    INTO deliveries_unique
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
   WHERE n.nspname = 'app'
     AND t.relname = 'wecom_group_deliveries'
     AND c.conname = 'wecom_group_deliveries_unique'
     AND c.contype = 'u';

  IF active_project_idx <> 1
     OR active_chat_idx <> 1
     OR pending_idx <> 1
     OR deliveries_unique <> 1 THEN
    RAISE EXCEPTION 'project wecom group indexes are incomplete';
  END IF;

  SELECT p.prosecdef, pg_get_userbyid(p.proowner), p.proacl IS NOT NULL
    INTO function_security_definer, function_owner, function_has_explicit_acl
    FROM pg_proc p
   WHERE p.oid =
     'app.redeem_project_wecom_binding_code(bytea, text, text)'::regprocedure;

  IF function_security_definer IS NULL
     OR NOT function_security_definer
     OR function_owner <> 'app_owner'
     OR NOT function_has_explicit_acl THEN
    RAISE EXCEPTION
      'app.redeem_project_wecom_binding_code must be SECURITY DEFINER owned by app_owner with explicit ACL';
  END IF;

  IF EXISTS (
    SELECT 1
      FROM pg_proc p,
           LATERAL aclexplode(p.proacl) AS acl
     WHERE p.oid =
       'app.redeem_project_wecom_binding_code(bytea, text, text)'::regprocedure
       AND acl.grantee = 0
  ) THEN
    RAISE EXCEPTION
      'PUBLIC must not execute app.redeem_project_wecom_binding_code';
  END IF;

  SELECT has_function_privilege(
           'app_runtime',
           'app.redeem_project_wecom_binding_code(bytea, text, text)',
           'EXECUTE'
         )
    INTO runtime_function_execute;
  IF NOT runtime_function_execute THEN
    RAISE EXCEPTION
      'app_runtime must execute app.redeem_project_wecom_binding_code';
  END IF;

  SELECT
    has_table_privilege('app_runtime', 'app.project_wecom_binding_codes', 'SELECT')
    AND has_table_privilege('app_runtime', 'app.project_wecom_binding_codes', 'INSERT')
    AND has_table_privilege('app_runtime', 'app.project_wecom_binding_codes', 'UPDATE')
    AND NOT has_table_privilege('app_runtime', 'app.project_wecom_binding_codes', 'DELETE')
    AND has_table_privilege('app_runtime', 'app.project_wecom_groups', 'SELECT')
    AND has_table_privilege('app_runtime', 'app.project_wecom_groups', 'INSERT')
    AND has_table_privilege('app_runtime', 'app.project_wecom_groups', 'UPDATE')
    AND NOT has_table_privilege('app_runtime', 'app.project_wecom_groups', 'DELETE')
    AND has_table_privilege('app_runtime', 'app.wecom_group_deliveries', 'SELECT')
    AND has_table_privilege('app_runtime', 'app.wecom_group_deliveries', 'INSERT')
    AND has_table_privilege('app_runtime', 'app.wecom_group_deliveries', 'UPDATE')
    AND NOT has_table_privilege('app_runtime', 'app.wecom_group_deliveries', 'DELETE')
    INTO runtime_ok;
  IF NOT runtime_ok THEN
    RAISE EXCEPTION
      'app_runtime must have SELECT / INSERT / UPDATE and no DELETE on project wecom group tables';
  END IF;

  SELECT
    has_table_privilege('app_backup', 'app.project_wecom_binding_codes', 'SELECT')
    AND NOT has_table_privilege('app_backup', 'app.project_wecom_binding_codes', 'INSERT')
    AND NOT has_table_privilege('app_backup', 'app.project_wecom_binding_codes', 'UPDATE')
    AND NOT has_table_privilege('app_backup', 'app.project_wecom_binding_codes', 'DELETE')
    AND has_table_privilege('app_backup', 'app.project_wecom_groups', 'SELECT')
    AND NOT has_table_privilege('app_backup', 'app.project_wecom_groups', 'INSERT')
    AND NOT has_table_privilege('app_backup', 'app.project_wecom_groups', 'UPDATE')
    AND NOT has_table_privilege('app_backup', 'app.project_wecom_groups', 'DELETE')
    AND has_table_privilege('app_backup', 'app.wecom_group_deliveries', 'SELECT')
    AND NOT has_table_privilege('app_backup', 'app.wecom_group_deliveries', 'INSERT')
    AND NOT has_table_privilege('app_backup', 'app.wecom_group_deliveries', 'UPDATE')
    AND NOT has_table_privilege('app_backup', 'app.wecom_group_deliveries', 'DELETE')
    INTO backup_ok;
  IF NOT backup_ok THEN
    RAISE EXCEPTION
      'app_backup must have read-only access to project wecom group tables';
  END IF;

  SELECT pg_get_userbyid(p.proowner), pg_get_functiondef(p.oid)
    INTO purge_owner, purge_def
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname = 'app'
     AND p.proname = 'purge_project';

  IF purge_owner IS NULL OR purge_owner <> 'app_owner' THEN
    RAISE EXCEPTION 'app.purge_project ownership check failed';
  END IF;
  IF position('project_wecom_groups' IN purge_def) = 0
     OR position('project_wecom_binding_codes' IN purge_def) = 0
     OR position('wecom_group_deliveries' IN purge_def) = 0 THEN
    RAISE EXCEPTION
      'app.purge_project must delete project wecom group tables';
  END IF;
END
