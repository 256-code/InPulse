SET LOCAL ROLE app_owner;

-- ADR-081：组织（部门）成员分组与同组织可见（第一批）。
-- 口径：
--   1. 组织为全局平铺列表：id、name（btrim 后 1～100 字符）、row_version 与时间戳；
--      名称按 lower(btrim(name)) 函数唯一索引去重（同名不同大小写 / 前后空白视为冲突）；
--   2. app.users.organization_id 为可空外键：一名成员至多归属一个组织，未分配为 NULL；
--      删除组织 ON DELETE SET NULL，成员自动回到未分配，不级联删除用户数据；
--   3. 组织是配置维度而非业务历史：允许物理删除（审计留痕），不做软删除；
--   4. 应用需要 SELECT / INSERT / UPDATE / DELETE 全部授权（改名与删除走应用事务）；
--      备份只读授权显式补齐（ADR-020 fail closed，不依赖 ALTER DEFAULT PRIVILEGES）。

CREATE TABLE app.organizations (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (
    sequence name "app"."organizations_id_seq"
    INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1
  ),
  name TEXT NOT NULL,
  row_version INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT organizations_name_length_check
    CHECK (length(btrim(name)) BETWEEN 1 AND 100),
  CONSTRAINT organizations_row_version_check CHECK (row_version >= 1)
);

CREATE UNIQUE INDEX organizations_name_key
  ON app.organizations (lower(btrim(name)));

ALTER TABLE app.users
  ADD COLUMN organization_id INTEGER;

ALTER TABLE app.users
  ADD CONSTRAINT users_organization_fk
    FOREIGN KEY (organization_id) REFERENCES app.organizations(id)
    ON DELETE SET NULL ON UPDATE NO ACTION;

GRANT SELECT, INSERT, UPDATE, DELETE ON app.organizations TO app_runtime;
GRANT SELECT ON app.organizations TO app_backup;

-- 部署校验：表、列、约束、函数唯一索引与授权口径必须同时成立。
DO $$
DECLARE
  table_owner TEXT;
  name_length_constraint INTEGER;
  row_version_constraint INTEGER;
  name_index INTEGER;
  users_column INTEGER;
  organization_fk INTEGER;
  fk_delete_action TEXT;
BEGIN
  SELECT pg_get_userbyid(c.relowner)
    INTO table_owner
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'app'
     AND c.relname = 'organizations'
     AND c.relkind = 'r';

  IF table_owner IS NULL THEN
    RAISE EXCEPTION 'app.organizations was not created';
  END IF;
  IF table_owner <> 'app_owner' THEN
    RAISE EXCEPTION 'app.organizations must be owned by app_owner, got %', table_owner;
  END IF;

  SELECT count(*)
    INTO name_length_constraint
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
   WHERE n.nspname = 'app'
     AND t.relname = 'organizations'
     AND c.conname = 'organizations_name_length_check'
     AND c.contype = 'c';

  IF name_length_constraint <> 1 THEN
    RAISE EXCEPTION 'organizations_name_length_check is missing';
  END IF;

  SELECT count(*)
    INTO row_version_constraint
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
   WHERE n.nspname = 'app'
     AND t.relname = 'organizations'
     AND c.conname = 'organizations_row_version_check'
     AND c.contype = 'c';

  IF row_version_constraint <> 1 THEN
    RAISE EXCEPTION 'organizations_row_version_check is missing';
  END IF;

  SELECT count(*)
    INTO name_index
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'app'
     AND c.relname = 'organizations_name_key'
     AND c.relkind = 'i';

  IF name_index <> 1 THEN
    RAISE EXCEPTION 'organizations_name_key unique index is missing';
  END IF;

  SELECT count(*)
    INTO users_column
    FROM pg_attribute a
    JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'app'
     AND c.relname = 'users'
     AND a.attname = 'organization_id'
     AND a.attnum > 0
     AND NOT a.attisdropped;

  IF users_column <> 1 THEN
    RAISE EXCEPTION 'app.users.organization_id is missing';
  END IF;

  SELECT count(*)
    INTO organization_fk
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
   WHERE n.nspname = 'app'
     AND t.relname = 'users'
     AND c.conname = 'users_organization_fk'
     AND c.contype = 'f';

  IF organization_fk <> 1 THEN
    RAISE EXCEPTION 'users_organization_fk is missing';
  END IF;

  SELECT confdeltype
    INTO fk_delete_action
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
   WHERE n.nspname = 'app'
     AND t.relname = 'users'
     AND c.conname = 'users_organization_fk';

  IF fk_delete_action IS DISTINCT FROM 'n' THEN
    RAISE EXCEPTION 'users_organization_fk must be ON DELETE SET NULL, got %', fk_delete_action;
  END IF;

  IF NOT (
    has_table_privilege('app_runtime', 'app.organizations', 'SELECT')
    AND has_table_privilege('app_runtime', 'app.organizations', 'INSERT')
    AND has_table_privilege('app_runtime', 'app.organizations', 'UPDATE')
    AND has_table_privilege('app_runtime', 'app.organizations', 'DELETE')
  ) THEN
    RAISE EXCEPTION 'app_runtime must have SELECT / INSERT / UPDATE / DELETE on app.organizations';
  END IF;

  IF NOT has_table_privilege('app_backup', 'app.organizations', 'SELECT')
     OR has_table_privilege('app_backup', 'app.organizations', 'INSERT')
     OR has_table_privilege('app_backup', 'app.organizations', 'UPDATE')
     OR has_table_privilege('app_backup', 'app.organizations', 'DELETE') THEN
    RAISE EXCEPTION 'app_backup must have read-only access to app.organizations';
  END IF;
END
$$;
